//! 共享的 Vue 运行时（供运行期加载的 UI 扩展使用）。
//!
//! 这个文件**只做再导出**，存在的理由是 vite 多入口需要一个真实文件作为
//! chunk 的锚点：壳与所有扩展因此拿到**同一个** `vue` 模块实例。
//!
//! ## 为什么必须是同一个实例
//!
//! Vue 的响应式、`provide/inject`、`instanceof` 判断都靠模块级单例。两份 vue
//! 的表现是：组件能渲染但 `ref` 不触发更新、注入拿不到、`Teleport` 目标错乱，
//! 而报错通常只有一行且指向别处。所以 import map 把裸标识符 `vue` 指到这里的
//! 产物，模块构建时也把 `vue` externalize 掉——两侧都指向同一个 URL。

export * from 'vue';
